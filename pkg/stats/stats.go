// Package stats dumps sanitized PostgreSQL planner statistics so a schema can
// be planned against production-scale cardinalities without copying any data.
//
// The output is a SQL file of pg_restore_relation_stats / pg_restore_attribute_stats
// calls (PostgreSQL 18+). Only cardinality-shaped statistics are exported:
// reltuples, relpages, relallvisible, and per-column n_distinct, null_frac and
// avg_width. Value-bearing statistics (most_common_vals, histogram_bounds) are
// deliberately never read, so the artifact is safe to commit — it cannot leak
// real column values such as phone numbers or emails.
package stats

import (
	"context"
	"database/sql"
	"fmt"
	"os"
	"strings"

	"github.com/lucasefe/seedup/pkg/pgconn"
)

// Options configures a stats dump.
type Options struct {
	Output        string   // Output file (empty = stdout)
	Schemas       []string // Schemas to include (empty = all non-system)
	ExcludeTables []string // Table names to exclude (unqualified)
}

// Dumper reads planner statistics from a database.
type Dumper struct{}

// New creates a new Dumper.
func New() *Dumper { return &Dumper{} }

// Dump writes the sanitized statistics SQL to the configured output.
func (d *Dumper) Dump(ctx context.Context, dbURL string, opts Options) error {
	out, err := d.DumpString(ctx, dbURL, opts)
	if err != nil {
		return err
	}
	if opts.Output == "" {
		fmt.Print(out)
		return nil
	}
	return os.WriteFile(opts.Output, []byte(out), 0644)
}

// DumpString reads the statistics and returns the SQL as a string.
func (d *Dumper) DumpString(ctx context.Context, dbURL string, opts Options) (string, error) {
	db, err := pgconn.Open(dbURL)
	if err != nil {
		return "", err
	}
	defer db.Close()

	var version int
	if err := db.QueryRowContext(ctx, "SHOW server_version_num").Scan(&version); err != nil {
		return "", fmt.Errorf("reading server version: %w", err)
	}

	exclude := map[string]bool{}
	for _, t := range opts.ExcludeTables {
		exclude[t] = true
	}

	var b strings.Builder
	b.WriteString("-- Generated by `seedup stats`. Sanitized planner statistics.\n")
	b.WriteString("-- Cardinality only: no most_common_vals / histogram_bounds, no row data.\n")
	b.WriteString("-- Apply against a migrated (data-less) schema before planning queries.\n")
	b.WriteString("BEGIN;\n")

	rels, err := d.relations(ctx, db, opts.Schemas)
	if err != nil {
		return "", err
	}
	for _, r := range rels {
		if exclude[r.name] {
			continue
		}
		b.WriteString(r.sql(version))
		attrs, err := d.attributes(ctx, db, r.schema, r.name)
		if err != nil {
			return "", err
		}
		for _, a := range attrs {
			b.WriteString(a.sql(r.schema, r.name, version))
		}
	}

	b.WriteString("COMMIT;\n")
	return b.String(), nil
}

type relation struct {
	schema        string
	name          string
	relpages      int64
	reltuples     float64
	relallvisible int64
}

func (r relation) sql(version int) string {
	return fmt.Sprintf(
		"SELECT pg_catalog.pg_restore_relation_stats(\n"+
			"  'schemaname', %s,\n"+
			"  'relname', %s,\n"+
			"  'relpages', %d::integer,\n"+
			"  'reltuples', %g::real,\n"+
			"  'relallvisible', %d::integer,\n"+
			"  'version', %d::integer);\n",
		sqlStr(r.schema), sqlStr(r.name), r.relpages, r.reltuples, r.relallvisible, version)
}

func (d *Dumper) relations(ctx context.Context, db *sql.DB, schemas []string) ([]relation, error) {
	query := `
SELECT n.nspname, c.relname, c.relpages, c.reltuples, c.relallvisible
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE c.relkind IN ('r', 'p')
  AND n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
  AND c.reltuples >= 0`
	var args []any
	if len(schemas) > 0 {
		query += " AND n.nspname = ANY($1)"
		args = append(args, pqArray(schemas))
	}
	query += " ORDER BY n.nspname, c.relname"

	rows, err := db.QueryContext(ctx, query, args...)
	if err != nil {
		return nil, fmt.Errorf("querying relations: %w", err)
	}
	defer rows.Close()

	var out []relation
	for rows.Next() {
		var r relation
		if err := rows.Scan(&r.schema, &r.name, &r.relpages, &r.reltuples, &r.relallvisible); err != nil {
			return nil, err
		}
		out = append(out, r)
	}
	return out, rows.Err()
}

type attribute struct {
	name      string
	inherited bool
	nullFrac  float64
	avgWidth  int64
	nDistinct float64
}

func (a attribute) sql(schema, table string, version int) string {
	return fmt.Sprintf(
		"SELECT pg_catalog.pg_restore_attribute_stats(\n"+
			"  'schemaname', %s,\n"+
			"  'relname', %s,\n"+
			"  'attname', %s,\n"+
			"  'inherited', %t::boolean,\n"+
			"  'null_frac', %g::real,\n"+
			"  'avg_width', %d::integer,\n"+
			"  'n_distinct', %g::real,\n"+
			"  'version', %d::integer);\n",
		sqlStr(schema), sqlStr(table), sqlStr(a.name), a.inherited,
		a.nullFrac, a.avgWidth, a.nDistinct, version)
}

func (d *Dumper) attributes(ctx context.Context, db *sql.DB, schema, table string) ([]attribute, error) {
	rows, err := db.QueryContext(ctx, `
SELECT attname, inherited, null_frac, avg_width, n_distinct
FROM pg_stats
WHERE schemaname = $1 AND tablename = $2
ORDER BY attname`, schema, table)
	if err != nil {
		return nil, fmt.Errorf("querying attributes for %s.%s: %w", schema, table, err)
	}
	defer rows.Close()

	var out []attribute
	for rows.Next() {
		var a attribute
		if err := rows.Scan(&a.name, &a.inherited, &a.nullFrac, &a.avgWidth, &a.nDistinct); err != nil {
			return nil, err
		}
		out = append(out, a)
	}
	return out, rows.Err()
}

// sqlStr renders a Go string as a single-quoted SQL literal.
func sqlStr(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

// pqArray formats a string slice as a Postgres text array literal for lib/pq.
func pqArray(vals []string) string {
	quoted := make([]string, len(vals))
	for i, v := range vals {
		quoted[i] = `"` + strings.ReplaceAll(v, `"`, `\"`) + `"`
	}
	return "{" + strings.Join(quoted, ",") + "}"
}
